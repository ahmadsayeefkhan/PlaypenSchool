#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Keeps the hand-built home page in step with the shared shell (Python 3 standard library only).

build/build.py never writes site/index.html. This separate tool copies four things from build/shell.py and
build/nav.json into marked regions of the home, and nothing else:

    seo     canonical, Open Graph, Twitter tags and the School JSON-LD (inside <head>)
    nav     the six links of the header's primary navigation
    menu    the full-screen menu (groups, their pages, preview images, utility links, phone lines)
    footer  the footer (address, phone lines, link columns, legal row, "Website by Defined Solution")

Regions are fenced in index.html by comment lines:

    <!-- pp:begin footer -->  ...generated, do not edit...  <!-- pp:end footer -->

    python build/sync_home.py            rewrite the regions (after changing nav.json or shell.py)
    python build/sync_home.py --check    exit 1 if the home has drifted from the shell (no write)
    python build/sync_home.py --init     first run only: add the fences around the existing blocks

Everything else in index.html (the scenes, the sheets, the Sheet drawer, the preloader, the scripts) is
left byte for byte as it is.
"""
import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import shell  # noqa: E402

REPO = os.path.dirname(HERE)
INDEX = os.path.join(REPO, 'site', 'index.html')
NOTE = '(generated by build/sync_home.py from build/nav.json and build/shell.py; edit those, not this block)'


def indent(text, n):
    pad = ' ' * n
    return '\n'.join((pad + line) if line.strip() else line for line in text.split('\n'))


def generate(nav):
    ctx = shell.Ctx(nav, '/')
    home = nav.by_slug['/']
    seo = shell.render_seo_head(ctx, home['title'], home['description'], shell.DEFAULT_OG_IMAGE, shell.DEFAULT_OG_SIZE,
                                shell.DEFAULT_OG_ALT, 'website', False, True, with_title=False)
    seo += '\n<script type="application/ld+json">\n%s\n</script>' % shell.home_jsonld(nav)
    return {
        'seo': seo,
        'nav': indent(shell.render_primary_links(ctx, None), 0).replace('\n      ', '\n      '),
        'menu': shell.render_menu(ctx, None),
        'footer': shell.render_footer(ctx),
    }


FENCE = r'(<!-- pp:begin %s[^>]*-->)(.*?)(<!-- pp:end %s -->)'


def init_fences(text):
    """Wrap the existing blocks with fences (first run only)."""
    def wrap(name, pattern, text, group_start=None):
        if '<!-- pp:begin %s' % name in text:
            return text
        m = re.search(pattern, text, re.S)
        if not m:
            raise SystemExit('init: could not find the %s block in index.html' % name)
        s, e = m.span(1)
        return text[:s] + '<!-- pp:begin %s %s -->\n' % (name, NOTE) + m.group(1) + '\n<!-- pp:end %s -->' % name + text[e:]
    text = wrap('seo', r'(<meta name="description".*?<meta name="twitter:image"[^>]*>)', text)
    if '<!-- pp:begin nav' not in text:
        m = re.search(r'(<nav id="nav-primary" class="nav__primary" aria-label="Primary">\n)(.*?)(\n    </nav>)', text, re.S)
        if not m:
            raise SystemExit('init: could not find #nav-primary')
        text = text[:m.start(2)] + '      <!-- pp:begin nav %s -->\n' % NOTE + m.group(2) + '\n      <!-- pp:end nav -->' + text[m.end(2):]
    text = wrap('menu', r'(<div id="menu" class="menu".*?\n</div>)(?=\n\n<div id="present")', text)
    text = wrap('footer', r'(<footer id="contact" class="foot is-night">.*?</footer>)', text)
    return text


def apply(text, regions):
    out = text
    for name, content in regions.items():
        rx = re.compile(FENCE % (name, name), re.S)
        m = rx.search(out)
        if not m:
            raise SystemExit('the fence "pp:begin %s ... pp:end %s" is missing in index.html (run --init once)' % (name, name))
        body = content if name != 'nav' else indent(content, 0)
        pad = '      ' if name == 'nav' else ''
        out = out[:m.start(2)] + '\n' + (pad + body if name == 'nav' else body) + '\n' + (pad if name == 'nav' else '') + out[m.end(2):]
    return out


def main(argv=None):
    ap = argparse.ArgumentParser(description='Sync the home page chrome with the shell.')
    ap.add_argument('--check', action='store_true', help='report drift, write nothing')
    ap.add_argument('--init', action='store_true', help='add the fences to index.html (first run)')
    args = ap.parse_args(argv)
    nav = shell.Nav.load(os.path.join(HERE, 'nav.json'))
    errs, _ = nav.validate()
    if errs:
        print('nav.json has errors:\n  ' + '\n  '.join(errs))
        return 1
    with open(INDEX, 'r', encoding='utf-8') as f:
        text = f.read()
    if args.init:
        text = init_fences(text)
    new = apply(text, generate(nav))
    if args.check:
        if new != text:
            print('site/index.html has drifted from build/shell.py and nav.json: run python build/sync_home.py')
            return 1
        print('site/index.html is in step with the shell')
        return 0
    if new != text or args.init:
        with open(INDEX, 'w', encoding='utf-8', newline='\n') as f:
            f.write(new)
        print('site/index.html: regions seo, nav, menu, footer written')
    else:
        print('site/index.html already in step')
    return 0


if __name__ == '__main__':
    sys.exit(main())
