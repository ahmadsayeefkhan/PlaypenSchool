def tile_sizes(n, i, shape=''):
    """`sizes` for the i-th tile of an album grid of n frames, matching gallery.css (alb-grid--1 ... --8 and the default
    three-up grid). Final review 2026-10-25: one '30vw' for every tile made the browser load the 480 px file for tiles
    drawn 564, 765 or 1169 px wide."""
    if n == 1:
        if shape == 'alb-shape--wide':
            return LEAD
        if shape in ('alb-shape--portrait', 'alb-shape--square'):
            return '(min-width: 640px) 560px, 100vw'
        return '(min-width: 1024px) 780px, (min-width: 640px) 84vw, 100vw'
    if n in (2, 4):
        return HALF
    if n == 3:
        return THIRD
    if n == 5:
        return LEAD if i == 0 else '(min-width: 1240px) 290px, (min-width: 1200px) 23vw, (min-width: 640px) 48vw, 100vw'
    if n == 7:
        return LEAD if i == 0 else THIRD
    if n == 8:
        return QUARTER
    return '(min-width: 1240px) 390px, (min-width: 1024px) 31vw, 48vw'


def hub_sort_key(albums):
    """Albums with frames: newest year first (sort_year counts as a year for the order only), then undated ones by number of
    frames (most first) in the school's order."""
    pos = {a['slug']: i for i, a in enumerate(albums)}
    def key(a):
        years = [int(y) for y in a['years']] + ([int(a['sort_year'])] if a.get('sort_year') else [])
        if years:
            return (0, -max(years), pos[a['slug']])
        return (1, -len(a['frames']), pos[a['slug']])
    return key


def card(a):
    slug = a['slug']
    year = ' '.join(a['years']) or 'none'
    cover = cover_of(a)
    pos = cover_pos(a)
    style = ' style="--pos: %s"' % pos if pos else ''
    frame = '<div class="alb-card__frame"%s>%s</div>' % (style, img(cover, CARD_SIZES, card_widths(cover['src'])))
    meta = '<span>%s</span>' % KIND[a['type']] + ('<span>%s</span>' % years_label(a) if a['years'] else '')
    return ('      <li class="alb-card" data-tags="%s" data-year="%s">\n'
            '        %s\n'
            '        <p class="alb-card__meta">%s</p>\n'
            '        <h3 class="alb-card__title"><a class="alb-card__link" href="{{link:/gallery/%s/}}">%s</a></h3>\n'
            '        <p class="alb-card__count"><b>%s shown</b>, %d in the album</p>\n'
            '      </li>' % (a['type'], year, frame, meta, slug, e(a['name']), plural(len(a['frames'])), a['count']))


def more_item(a):
    meta = KIND[a['type']] + (' &middot; %s' % years_label(a) if a['years'] else '') + ' &middot; ' + (
        plural(a['count']) if a['count'] else 'no photographs yet')
