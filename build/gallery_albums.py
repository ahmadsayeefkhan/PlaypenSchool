def e(t):
    return escape(t, quote=True)


def largest(src):
    """The largest JPG of a stem for the viewer's link (img/gal-x -> img/gal-x-1200.jpg; a single file is itself)."""
    if re.search(r'\.(jpe?g|png)$', src):
        return src
    folder, _, stem = src.rpartition('/')
    best = None
    for name in os.listdir(os.path.join(IMG, folder)):
        m = re.match(re.escape(stem) + r'-(\d{3,4})\.jpe?g$', name)
        if m and (best is None or int(m.group(1)) > best[0]):
            best = (int(m.group(1)), name)
    if not best:
        raise SystemExit('no JPG found for %s' % src)
    return folder + '/' + best[1]


def years_label(a):
    y = a['years']
    return ' and '.join(y) if y else ''


def plural(n, one='photograph'):
    return '%d %s%s' % (n, one, '' if n == 1 else 's')


def count_line(a):
    """Positive wording: what is shown first, the album's size second."""
    shown, total = len(a['frames']), a['count']
    if total == 0:
        return 'No photographs in the album yet'
    if shown == 0:
        return '%s in the album, none shown yet' % plural(total)
    return '%s shown, %d in the album' % (plural(shown), total)


def cover_of(a):
    """The frame on the hub card and the album's hero plate: the JSON's cover, else the first frame."""
    if not a['frames']:
        return None
    want = a.get('cover')
    for fr in a['frames']:
        if fr['src'] == want:
            return fr
    return a['frames'][0]


def cover_pos(a):
    fr = cover_of(a)
    return a.get('cover_pos') or (fr.get('pos') if fr else None)


def img(fr, sizes, extra='', alt=None):
    return '{{img src="%s" alt="%s" sizes="%s"%s}}' % (fr['src'], e(alt or fr['alt']), sizes, extra)


def widths_for(src):
    # final review 2026-10-25: every width that exists goes into the srcset (the 1200/1440 files were left out, so a lead tile
    # drawn 1169 px wide loaded the 480 or 960 file and stretched it); the browser picks by `sizes` below
    return ''


def card_widths(src):
    # the hub's album cards and its slide strip keep their two widths (a card is at most 23 to 30 vw)
    return ' widths="480,960"' if src.startswith('img/gal-') else ' widths="960"'


