def more_cols(n):
    """Where the folded list sits in the card grid at 2, 3 and 4 columns (gallery.css reads --more-c2/3/4): in the free cells
    of the last row of covers when two or more are free, else across a whole row (round-2 fixes, 2026-10-25)."""
    out = []
    for cols in (2, 3, 4):
        rem = n % cols
        free = cols - rem if rem else 0
        out.append('--more-c%d: %s' % (cols, ('%d / -1' % (rem + 1)) if free >= 2 else '1 / -1'))
    return '; '.join(out)


NUMWORDS = {20: 'Twenty', 21: 'Twenty-one', 22: 'Twenty-two', 23: 'Twenty-three', 24: 'Twenty-four', 25: 'Twenty-five'}


def grid_class(n):
    """A grid that fits the number of frames (review r1, 2026-10-24: seven is a wide lead and two rows of three, eight is
    two rows of four from 1024 px, so no row is left with a hole)."""
    return {1: 'alb-grid--1', 2: 'alb-grid--2', 3: 'alb-grid--3', 4: 'alb-grid--4', 5: 'alb-grid--5', 7: 'alb-grid--7', 8: 'alb-grid--8'}.get(n, '')


def frame_size(src):
    """(width, height) of the largest JPG of a frame, read from the file header."""
    return media.read_size(os.path.join(IMG, *largest(src).split('/')))


def single_shape(fr):
    """A one-frame album shows the frame at its own ratio and never wider than its source (review r1, 2026-10-24: the
    3:2 box upscaled a 3:1 banner and two 480 px frames). Returns (shape class, the inline --alb-max)."""
    size = frame_size(fr['src'])
    if not size:
        return '', ''
    w, h = size
    r = w / float(h)
    shape = 'alb-shape--wide' if r >= 2.0 else 'alb-shape--portrait' if r < 0.9 else 'alb-shape--square' if r <= 1.1 else 'alb-shape--land'
    return shape, ' style="--alb-max: %dpx"' % w


def grid_frames(a):
    """The frames in an album's grid: all of them, minus the cover when the cover is the hero plate (three or more frames),
    so the same photograph is never shown twice on one page (review r1, 2026-10-24)."""
    frames = a['frames']
    if has_hero(a):
        cover = cover_of(a)
        return [fr for fr in frames if fr is not cover]
    return frames


def has_hero(a):
    """The album opens on the mounted plate of its cover only when it has three or more frames; a two-frame album shows
    both frames large instead, a one-frame album shows its frame once."""
    return len(a['frames']) >= 3


