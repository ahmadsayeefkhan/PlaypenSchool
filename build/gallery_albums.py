def nav_entries(albums):
    rows = []
    for i, a in enumerate(albums, 1):
        desc = '%s: an album from the school gallery of Playpen School, Dhaka, in frames where no child can be recognised.' % a['name']
        if len(desc) > 170:
            desc = '%s: an album from the gallery of Playpen School, Dhaka.' % a['name']
        if len(desc) < 60:
            desc = desc[:-1] + ', in frames where no child can be recognised.'
        # an album may carry its own one-line "summary"; otherwise the note, cut at a word when it is long (a cut can leave a
        # sentence hanging, as G03's did: "... with their."; such an album gets a "summary" in gallery-albums.json)
        summary = a.get('summary') or (a['note'] if len(a['note']) <= 140 else a['note'][:137].rsplit(' ', 1)[0] + '.')
        # albums without a frame are built noindex (album_page); nav.json says so too, so sitemap.xml, the search index,
        # check.py and the sitemap page's album list all read the one flag (integrator, 2026-10-25)
        flag = '' if a['frames'] else ', "noindex": true'
        rows.append('    {\n'
                    '      "id": "G%02d", "slug": "/gallery/%s/", "label": %s, "title": %s, "template": "T10", "parent": "/gallery/", "group": "community", "menu": false, "footer": null%s,\n'
                    '      "description": %s,\n'
                    '      "summary": %s\n'
                    '    },' % (i, a['slug'], json.dumps(a['name'], ensure_ascii=False), json.dumps('Photographs of ' + a['name'], ensure_ascii=False),
                               flag, json.dumps(desc, ensure_ascii=False), json.dumps(summary, ensure_ascii=False)))
    return '\n'.join(rows)


def update_nav(albums):
    with open(NAV, 'r', encoding='utf-8') as f:
        text = f.read()
    text = re.sub(r'\n    \{\n      "id": "G\d\d".*?\n    \},', '', text, flags=re.S)     # this script's own earlier entries
    m = re.search(r'\n    \{\n      "id": "P38".*?\n    \},', text, flags=re.S)
    if not m:
        raise SystemExit('nav.json: the /gallery/ entry (P38) was not found')
    text = text[:m.end()] + '\n' + nav_entries(albums) + text[m.end():]
    json.loads(text)                     # still valid JSON
    with open(NAV, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    with open(DATA, 'r', encoding='utf-8') as f:
        albums = json.load(f)['albums']
    slugs = [a['slug'] for a in albums]
    assert len(slugs) == len(set(slugs)), 'duplicate album slug'
    os.makedirs(PAGES, exist_ok=True)
    keep = {'index.html'} | {s + '.html' for s in slugs}
    for name in os.listdir(PAGES):                 # an album that was renamed or removed: its old source goes
        if name.endswith('.html') and name not in keep:
            os.remove(os.path.join(PAGES, name))
    def write(path, text):
        with open(path, 'w', encoding='utf-8', newline='\n') as f:
            f.write(text)
    write(os.path.join(PAGES, 'index.html'), index_page(albums))
    chain = sorted([a for a in albums if a['frames']], key=hub_sort_key(albums))   # the pager runs among albums with frames, in hub order
    at = {a['slug']: i for i, a in enumerate(chain)}
    for a in albums:
        if a['slug'] in at:
            i = at[a['slug']]
            prev, nxt = (chain[i - 1] if i else None), (chain[i + 1] if i + 1 < len(chain) else None)
        else:
            prev = nxt = None
        write(os.path.join(PAGES, a['slug'] + '.html'), album_page(a, prev, nxt, albums))
    if '--no-nav' not in argv:
        update_nav(albums)
    print('gallery: %d albums (%d with frames), %d frames; wrote build/pages/gallery/%s' % (
        len(albums), len(chain), sum(len(a['frames']) for a in albums), '' if '--no-nav' in argv else ' and %d nav.json entries' % len(albums)))


if __name__ == '__main__':
    main()
